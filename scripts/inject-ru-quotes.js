function buildQuotesBlock(translations) {
  const items = translations.map(text => {
    const escaped = text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    return `      { "text": "${escaped}" }`;
  }).join(',\n');
  return `    "quotes": [\n${items}\n    ]`;
}

function injectQuotes(filePath, id) {
  const trans = TRANSLATIONS[id];
  if (!trans) return { skipped: true, reason: 'no translations' };

  let src = fs.readFileSync(filePath, 'utf8');

  // Check if ru.quotes already exists — be idempotent. We look for `"quotes"` inside the ru block range only.
  // Find the `"ru": {` opening:
  const ruMatch = src.match(/"ru":\s*\{/);
  if (!ruMatch) return { skipped: true, reason: 'no ru block' };

  const ruStart = ruMatch.index + ruMatch[0].length;
  // Find matching close brace, tracking depth and respecting string literals.
  let depth = 1;
  let i = ruStart;
  let inStr = false;
  let escNext = false;
  while (i < src.length && depth > 0) {
    const c = src[i];
    if (escNext) { escNext = false; i++; continue; }
    if (c === '\\') { escNext = true; i++; continue; }
    if (c === '"') { inStr = !inStr; i++; continue; }
    if (!inStr) {
      if (c === '{') depth++;
      else if (c === '}') depth--;
    }
    if (depth === 0) break;
    i++;
  }
  if (depth !== 0) return { skipped: true, reason: 'unbalanced ru block' };
  const ruEnd = i; // index of the closing `}` of the ru block.

  const ruContent = src.slice(ruStart, ruEnd);
  if (/"quotes"\s*:/.test(ruContent)) {
    return { skipped: true, reason: 'ru.quotes already exists' };
  }

  const quotesBlock = buildQuotesBlock(trans);

  // Find last non-whitespace before ruEnd to know whether to add leading comma.
  let insertPos = ruEnd;
  let backIdx = ruEnd - 1;
  while (backIdx > ruStart && /\s/.test(src[backIdx])) backIdx--;
  const lastChar = src[backIdx];
  const needsLeadingComma = lastChar !== ',' && lastChar !== '{';

  const insertion = (needsLeadingComma ? ',\n' : '\n') + quotesBlock + '\n  ';
  src = src.slice(0, insertPos) + insertion + src.slice(insertPos);

  fs.writeFileSync(filePath, src);
  return { ok: true, count: trans.length };
}

const dir = path.join(__dirname, '..', 'data', 'systems');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.js') && !f.startsWith('_'));
let ok = 0, skipped = 0;
for (const f of files) {
  const id = f.replace(/\.js$/, '');
  const r = injectQuotes(path.join(dir, f), id);
  if (r.ok) {
    ok++;
    console.log(`  ${id}: injected ${r.count} RU quote(s)`);
  } else {
    skipped++;
    console.log(`  ${id}: skipped (${r.reason})`);
  }
}
console.log(`\nTotal: ${ok} files updated, ${skipped} skipped.`);
